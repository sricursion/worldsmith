// Prints clip names, skinned meshes and joint names for the KayKit Adventurers GLBs.
// Parses the GLB JSON chunk directly: 12-byte header, then chunk length/type, then JSON.
// Usage: node tests/engine/inspect-glb.mjs [--md] [--json]
//   --md prints the markdown stored as tests/engine/kaykit-rig-report.md (minus the hand-written clip mapping section).
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', '..', 'assets', 'third_party', 'kaykit-adventurers');
export const FILES = ['Barbarian', 'Knight', 'Mage', 'Rogue', 'Rogue_Hooded'];

export function readGlbJson(path) {
  const buf = readFileSync(path);
  if (buf.readUInt32LE(0) !== 0x46546c67) throw new Error(`${path}: not a GLB`);
  const chunkLen = buf.readUInt32LE(12);
  const chunkType = buf.readUInt32LE(16);
  if (chunkType !== 0x4e4f534a) throw new Error(`${path}: first chunk is not JSON`);
  return JSON.parse(buf.subarray(20, 20 + chunkLen).toString('utf8'));
}

export function inspect(name) {
  const json = readGlbJson(join(dir, `${name}.glb`));
  const nodes = json.nodes ?? [];
  const clips = (json.animations ?? []).map((a) => a.name ?? '');
  const skinned = nodes.filter((n) => n.skin !== undefined && n.mesh !== undefined).map((n) => n.name ?? '');
  const joints = new Set();
  for (const s of json.skins ?? []) for (const j of s.joints ?? []) joints.add(nodes[j]?.name ?? `#${j}`);
  return {
    name,
    clips,
    skinned,
    joints: [...joints].sort(),
    skinCount: (json.skins ?? []).length,
    materials: (json.materials ?? []).map((m) => m.name ?? ''),
    images: (json.images ?? []).length,
    extensions: json.extensionsUsed ?? [],
  };
}

export function run() {
  const reports = FILES.map(inspect);
  const base = reports[0];
  const diffs = reports.slice(1).map((r) => ({
    name: r.name,
    missing: base.joints.filter((j) => !r.joints.includes(j)),
    extra: r.joints.filter((j) => !base.joints.includes(j)),
    clipsMissing: base.clips.filter((c) => !r.clips.includes(c)),
    clipsExtra: r.clips.filter((c) => !base.clips.includes(c)),
  }));
  return { reports, baseName: base.name, diffs };
}

const isMain = process.argv[1] !== undefined && process.argv[1].endsWith('inspect-glb.mjs');
if (isMain) {
  const { reports, baseName, diffs } = run();
  if (process.argv.includes('--md')) {
    const b = reports[0];
    const lines = ['# KayKit Adventurers rig report', '', 'Generated by `node tests/engine/inspect-glb.mjs --md` from the GLB JSON chunks.', ''];
    lines.push('| File | Clips | Joints | Skins | Skinned meshes |', '|---|---|---|---|---|');
    for (const r of reports) lines.push(`| ${r.name}.glb | ${r.clips.length} | ${r.joints.length} | ${r.skinCount} | ${r.skinned.join(', ')} |`);
    lines.push('', '## Bone-name diff against ' + baseName, '');
    for (const d of diffs) lines.push(`- ${d.name}: missing [${d.missing.join(', ')}], extra [${d.extra.join(', ')}]`);
    const same = diffs.every((d) => d.missing.length === 0 && d.extra.length === 0);
    lines.push('', same ? 'Result: identical bone-name sets. One rig family; every base shares one clip map.' : 'Result: bone sets differ, see above.');
    lines.push('', '## Clip-name diff against ' + baseName, '');
    for (const d of diffs) lines.push(`- ${d.name}: missing [${d.clipsMissing.join(', ')}], extra [${d.clipsExtra.join(', ')}]`);
    lines.push('', `## Joints (${b.joints.length})`, '', b.joints.join(', '));
    lines.push('', `## Clips (${b.clips.length})`, '', b.clips.join(', '));
    console.log(lines.join(String.fromCharCode(10)));
  } else if (process.argv.includes('--json')) {
    console.log(JSON.stringify({ reports, baseName, diffs }, null, 1));
  } else {
    for (const r of reports) {
      console.log(`== ${r.name}: ${r.clips.length} clips, ${r.joints.length} joints, ${r.skinCount} skins, ext=${r.extensions.join(',') || '-'}`);
      console.log(`skinned meshes: ${r.skinned.join(', ')}`);
      console.log(`clips: ${r.clips.join(' | ')}`);
      console.log(`joints: ${r.joints.join(', ')}`);
    }
    for (const d of diffs) {
      console.log(`diff ${baseName} vs ${d.name}: bones missing=[${d.missing.join(',')}] extra=[${d.extra.join(',')}] clipsMissing=[${d.clipsMissing.join(',')}] clipsExtra=[${d.clipsExtra.join(',')}]`);
    }
  }
}
